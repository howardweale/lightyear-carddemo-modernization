"""Conservative 2c structural partition of authenticated incomplete B06 streams.

A captured non-bootstrap class input is an application-derived witness. A JDK-only
captured-input candidate is NOT proof that generated bytes are image independent.
Call stacks are deliberately excluded: a caller alone is not generation input.
"""
import argparse, hashlib, json
from collections import Counter
from pathlib import Path
from lightyear_calibration.contracts import read_json, verify
from lightyear_control_tower.decisions import verify_envelope

PAYLOADS=('lambda_factory','definer','lambda_form_graph','class_data_graph')
PLATFORM_PREFIXES=('java.','javax.','jdk.','sun.','com.sun.','org.w3c.dom.','org.xml.sax.','org.ietf.jgss.','netscape.javascript.')
def platform_name(name):
    return name.lstrip('[').removeprefix('L').replace('/','.').startswith(PLATFORM_PREFIXES)
def class_references(value):
    if isinstance(value,dict):
        if {'class','class_object_id','loader'}<=value.keys():yield value
        for item in value.values():yield from class_references(item)
    elif isinstance(value,list):
        for item in value:yield from class_references(item)

def classify(record):
    refs=[ref for key in PAYLOADS for ref in class_references(record.get(key))]
    # Bootstrap is a runtime identity witness; package-prefix guesses are not used.
    application=[ref for ref in refs if ref['loader']!='bootstrap' and not platform_name(ref['class'])]
    if application:return 'application-derived-input', len(application)
    if any(ref['loader']!='bootstrap' for ref in refs):return 'unresolved-platform-loader-input', len(refs)
    if refs:return 'bootstrap-only-captured-input-candidate', len(refs)
    return 'unresolved-no-class-input-witness', 0

def partition(folder, public_key):
    census=read_json(folder/'frame-census.json');failure=read_json(folder/'failure.json')
    for envelope in (census,failure):
        if not verify_envelope(envelope,public_key) or envelope['complete'] is not False:raise ValueError('classification-signature-or-scope')
    digest=hashlib.sha256();previous=None;events=0;counts=Counter();methods={};witnesses=hashlib.sha256()
    with (folder/'events.jsonl').open('rb') as stream:
        while line:=stream.readline(4*1024*1024+1):
            if len(line)>4*1024*1024:raise ValueError('classification-line-cap')
            digest.update(line);row=json.loads(line);verify(row);event=row['event'];events+=1
            if event['sequence']!=events or row['previous_sha256']!=previous:raise ValueError('classification-chain')
            previous=row['content_sha256']
            if event['kind']=='generation-entry':
                category,n=classify(event['record']);counts[category]+=1
                methods.setdefault(event['record']['entry_method'],Counter())[category]+=1
                # Aggregate witness digest binds exact event and rule result; no raw input escapes.
                witnesses.update(json.dumps([events,previous,category,n],separators=(',',':')).encode()+b'\n')
    for envelope in (census,failure):
        if events!=envelope['event_count'] or previous!=envelope['last_event_sha256']:raise ValueError('classification-tail-binding')
    if digest.hexdigest()!=census['event_file_sha256'] or census['plan_sha256']!=failure['plan_sha256'] or census['lane']!=failure['lane']:raise ValueError('classification-stream-binding')
    total=sum(counts.values())
    return dict(schema='b06-alternatives-2c/1',stream_sha256=digest.hexdigest(),events=events,generation_entries=total,
        counts=dict(counts),percentages={k:100*v/total for k,v in counts.items()},methods=methods,witnesses_sha256=witnesses.hexdigest(),
        census_sha256=census['content_sha256'],failure_sha256=failure['content_sha256'],signatures_verified=2,
        public_key_sha256=hashlib.sha256(public_key).hexdigest(),image_independent_proven=0,complete_observation=False,
        provenance_replayed=False,qualification_credit=False,measurement_credit=False,model_calls=0)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--folder',type=Path,required=True)
    parser.add_argument('--public-key',type=Path,required=True);parser.add_argument('--out',type=Path,required=True);args=parser.parse_args()
    if args.out.resolve().is_relative_to(args.folder.resolve()):raise ValueError('output-inside-preserved-evidence')
    result=partition(args.folder,args.public_key.read_bytes())
    with args.out.open('x',encoding='utf-8') as output:json.dump(result,output,indent=2);output.write('\n')
