SELECT JSON_QUERY((SELECT COLUMN_NAME AS name, DATA_TYPE AS type FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA='dbo' AND TABLE_NAME='sales_by_store' ORDER BY ORDINAL_POSITION FOR JSON PATH)) AS columns,
JSON_QUERY((SELECT * FROM dbo.sales_by_store FOR JSON PATH, INCLUDE_NULL_VALUES)) AS rows
FOR JSON PATH, WITHOUT_ARRAY_WRAPPER;
